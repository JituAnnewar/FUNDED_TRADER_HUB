// Generates lib/geo/land-dots.ts: evenly spaced points (Fibonacci sphere) that fall on land.
// Run once: node scripts/gen-land-dots.mjs [count]. Output is committed, so the site needs no map data at runtime.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const N = Number(process.argv[2] ?? 16000);
const topo = JSON.parse(readFileSync(new URL("../node_modules/world-atlas/land-50m.json", import.meta.url), "utf8"));
const land = feature(topo, topo.objects.land);

const golden = Math.PI * (3 - Math.sqrt(5));
const out = [];
for (let i = 0; i < N; i++) {
  const y = 1 - (i / (N - 1)) * 2; // 1 → -1
  const lat = (Math.asin(y) * 180) / Math.PI;
  if (lat < -60) continue; // skip Antarctica: keeps the globe readable
  const lon = (((((i * golden * 180) / Math.PI) % 360) + 540) % 360) - 180;
  if (geoContains(land, [lon, lat])) out.push(Math.round(lat * 100), Math.round(lon * 100));
}

const buf = Buffer.from(new Int16Array(out).buffer);
mkdirSync(new URL("../lib/geo/", import.meta.url), { recursive: true });
writeFileSync(
  new URL("../lib/geo/land-dots.ts", import.meta.url),
  `// Generated by scripts/gen-land-dots.mjs from world-atlas (Natural Earth, public domain). Do not edit.\n` +
    `// Int16 pairs [lat*100, lon*100], base64.\n` +
    `export const LAND_DOT_COUNT = ${out.length / 2};\n` +
    `export const LAND_DOTS_B64 = "${buf.toString("base64")}";\n`,
);
console.log(`${out.length / 2} land dots, ${buf.length} bytes`);

// Static poster: orthographic view centred on India/Middle East, one <path> of round dots.
const LON0 = (55 * Math.PI) / 180;
const LAT0 = (18 * Math.PI) / 180;
const R = 480;
let d = "";
for (let i = 0; i < out.length; i += 2) {
  const lat = ((out[i] / 100) * Math.PI) / 180;
  const lon = ((out[i + 1] / 100) * Math.PI) / 180;
  const cosc = Math.sin(LAT0) * Math.sin(lat) + Math.cos(LAT0) * Math.cos(lat) * Math.cos(lon - LON0);
  if (cosc < 0.05) continue; // back side
  const x = 500 + R * Math.cos(lat) * Math.sin(lon - LON0);
  const y = 500 - R * (Math.cos(LAT0) * Math.sin(lat) - Math.sin(LAT0) * Math.cos(lat) * Math.cos(lon - LON0));
  d += `M${x.toFixed(1)} ${y.toFixed(1)}h0`;
}
mkdirSync(new URL("../public/", import.meta.url), { recursive: true });
writeFileSync(
  new URL("../public/globe-poster.svg", import.meta.url),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1000">` +
    `<defs><radialGradient id="g" cx="40%" cy="35%" r="70%"><stop offset="0" stop-color="#1a1f4d"/><stop offset=".7" stop-color="#0b0d24"/><stop offset="1" stop-color="#05060f"/></radialGradient>` +
    `<radialGradient id="a" r=".5"><stop offset=".9" stop-color="#7c5cff" stop-opacity=".35"/><stop offset="1" stop-color="#22d3ee" stop-opacity="0"/></radialGradient></defs>` +
    `<circle cx="500" cy="500" r="500" fill="url(#a)"/><circle cx="500" cy="500" r="${R}" fill="url(#g)"/>` +
    `<path d="${d}" stroke="#8b9bff" stroke-opacity=".75" stroke-width="5.5" stroke-linecap="round"/></svg>`,
);
console.log("poster written");
